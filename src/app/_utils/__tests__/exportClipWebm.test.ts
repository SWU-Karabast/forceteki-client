import { describe, it, expect, vi, afterEach } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse, normalizeEvents } from '@/lib/swupgn';
import { buildBeats } from '../replayBeats';
import { groupsByAdjacency } from '../swupgnWriter';
import { clipBeats, exportClipWebm } from '../exportClipWebm';

// clipBeats is the pure slice of exportClipWebm's frame loop (the rest is MediaRecorder,
// browser-only); this is what keeps the loop's beat selection honest.
const doc = parse(readFileSync(join(__dirname, '../../../lib/swupgn/__tests__/fixtures/game-463c3022.swupgn'), 'utf8'));
const events = normalizeEvents(doc.events, new Set());
const beats = buildBeats(events, { adjacency: groupsByAdjacency(doc.header) });

describe('clipBeats', () => {
    it('a clip over whole beats 7..12 yields exactly beats 7..12', () => {
        const lo = beats[7].start, hi = beats[12].end;
        expect(clipBeats(beats, lo, hi).map((b) => b.index)).toEqual([7, 8, 9, 10, 11, 12]);
    });

    it('a clip starting mid-beat still counts that beat once', () => {
        const b = beats.find((x) => x.end > x.start);
        expect(b).toBeDefined();
        expect(clipBeats(beats, b!.start + 1, b!.end)).toEqual([b]);
    });
});

// Generated by /ship coverage audit.
// Value: protects=a frame that throws mid-clip still stops the MediaRecorder and every canvas stream track, and the error reaches the caller; fails_when=the try/finally around the frame loop is removed or the track stop is dropped; why_new=only clipBeats was tested, never the loop's cleanup; seam=none (stubbed window/document/MediaRecorder globals); no_claim=real browser MediaRecorder/captureStream behaviour or the produced .webm
describe('exportClipWebm cleanup', () => {
    afterEach(() => vi.unstubAllGlobals());

    it('stops the recorder and the stream tracks when a frame throws', async () => {
        const track = { stop: vi.fn() };
        const stream = { getTracks: () => [track] };
        const ctx = new Proxy({}, { get: () => () => undefined, set: () => true });
        const recorder = { state: 'inactive', start: vi.fn(function (this: { state: string }) { this.state = 'recording'; }), stop: vi.fn(function (this: { state: string }) { this.state = 'inactive'; }), ondataavailable: null, onstop: null };
        const MR = Object.assign(vi.fn(() => recorder), { isTypeSupported: () => true });
        vi.stubGlobal('window', { MediaRecorder: MR });
        vi.stubGlobal('MediaRecorder', MR);
        vi.stubGlobal('document', { createElement: () => ({ getContext: () => ctx, captureStream: () => stream }) });

        const err = await exportClipWebm({
            doc, events, start: 0, end: events.length - 1,
            labelForSeq: () => { throw new Error('boom'); },
            nameAt: () => '',
        }).catch((e: Error) => e);

        expect((err as Error).message).toBe('boom');
        expect(recorder.start).toHaveBeenCalledTimes(1);
        expect(recorder.stop).toHaveBeenCalledTimes(1);
        expect(track.stop).toHaveBeenCalledTimes(1);
    });
});
